// Writes web/src/icons/paths.ts: the SVG path data for the Material Symbols
// glyphs pitwall uses, keyed by the semantic names in docs/design-system.md
// (2.14). The package is vendored as data, never installed as a dependency.
//
//   mkdir <new empty dir> && cd <it>
//   npm pack @material-symbols/svg-400@0.47.6
//   mkdir <another new empty dir>
//   tar -xzf material-symbols-svg-400-0.47.6.tgz -C <it>
//   npx tsx scripts/extract-icons.ts <it>/package
//
// The unpacked files are read as text and nothing in them is run. Each SVG must
// be a single path in Material Symbols' 960-unit viewBox, and each path may
// contain only path commands and numbers, so nothing else can reach the
// generated file.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE = '@material-symbols/svg-400';
/** Rounded, fill 0 (the files without the -fill suffix). The package's SVGs are weight 400, grade 0. */
const STYLE = 'rounded';
const VIEW_BOX = '0 -960 960 960';

/** Semantic name, then the Material Symbols glyph it uses. The table in docs/design-system.md, 2.14. */
const ICONS: Readonly<Record<string, string>> = {
  close: 'close',
  expand: 'chevron_right',
  // The down chevron, which Material Symbols used to call expand_more.
  select: 'keyboard_arrow_down',
  more: 'more_horiz',
  search: 'search',
  clear: 'cancel',
  add: 'add',
  copy: 'content_copy',
  copied: 'check',
  terminal: 'terminal',
  conversation: 'forum',
  send: 'send',
  stop: 'stop_circle',
  remove: 'delete',
  restart: 'restart_alt',
  retry: 'refresh',
  info: 'info',
  success: 'check_circle',
  warning: 'warning',
  error: 'error',
  repo: 'account_tree',
  directory: 'folder',
  external: 'open_in_new',
  latest: 'arrow_downward',
  back: 'arrow_back',
  keyboard: 'keyboard',
  'theme-system': 'computer',
  'theme-light': 'light_mode',
  'theme-dark': 'dark_mode',
};

const OUTPUT = fileURLToPath(new URL('../web/src/icons/paths.ts', import.meta.url));

function fail(message: string): never {
  console.error(`extract-icons: ${message}`);
  process.exit(1);
}

/** The one path's `d`, after checking the SVG is the shape the generated file assumes. */
function pathData(svg: string, file: string): string {
  const root = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (!root) fail(`${file} isn't a single <svg> element`);
  const [, attributes = '', body = ''] = root;
  const viewBox = /\bviewBox="([^"]*)"/.exec(attributes)?.[1];
  if (viewBox !== VIEW_BOX) fail(`${file} has viewBox "${viewBox ?? ''}", not "${VIEW_BOX}"`);
  const path = /^\s*<path d="([^"]*)"\s*\/>\s*$/.exec(body);
  if (!path) fail(`${file} isn't exactly one <path d="…"/> with no other attributes`);
  const d = path[1] ?? '';
  if (!/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/.test(d)) fail(`${file} has characters in its path data that aren't path commands or numbers`);
  return d;
}

const dir = process.argv[2];
if (!dir || process.argv.length > 3) fail('usage: npx tsx scripts/extract-icons.ts <unpacked package directory>');

const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { name?: unknown; version?: unknown; license?: unknown };
if (manifest.name !== PACKAGE) fail(`${dir} is ${String(manifest.name)}, not ${PACKAGE}`);
if (typeof manifest.version !== 'string' || !/^\d+\.\d+\.\d+$/.test(manifest.version)) fail('the package has no plain version');
if (manifest.license !== 'Apache-2.0') fail(`the package's licence is ${String(manifest.license)}, not Apache-2.0`);

const entries = Object.entries(ICONS).map(([name, glyph]) => {
  if (!/^[a-z0-9_]+$/.test(glyph) || !/^[a-z]+(?:-[a-z]+)*$/.test(name)) fail(`bad icon ${name}: ${glyph}`);
  const file = join(dir, STYLE, `${glyph}.svg`);
  // Single quotes, as in the rest of the code. Neither a name nor a checked path can contain one.
  const key = name.includes('-') ? `'${name}'` : name;
  return `  /** ${glyph} */\n  ${key}: '${pathData(readFileSync(file, 'utf8'), file)}',`;
});

const source = `// Generated by scripts/extract-icons.ts. Don't edit by hand: see that script to regenerate it.
//
// Material Symbols Rounded, from ${PACKAGE}@${manifest.version} (Apache License 2.0; see ./LICENSE
// and THIRD_PARTY_NOTICES.md): fill 0, weight 400, grade 0, at the 48 px optical size, the only one
// the package has. Keyed by the semantic names in docs/design-system.md (2.14), with each glyph's name
// above its path. Each path is in the ${VIEW_BOX} viewBox.

export const ICON_PATHS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;

writeFileSync(OUTPUT, source);
console.log(`extract-icons: wrote ${entries.length} icons from ${PACKAGE}@${manifest.version} to ${OUTPUT}`);
